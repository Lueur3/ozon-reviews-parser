"""Настройки парсера отзывов Ozon.

Все числа, влияющие на поведение сбора, собраны здесь и снабжены объяснением,
откуда взято значение. В коде не должно оставаться безымянных констант: если
Ozon изменит поведение, менять нужно одно место и понимать последствия.

Ссылок на конкретные товары здесь нет и не должно быть — товар всегда задаёт
пользователь аргументом командной строки.
"""
import logging
import random
from pathlib import Path

# --- что собираем ----------------------------------------------------------
# Период актуальности отзывов (в днях). Отзывы старше — отбрасываются.
REVIEW_PERIOD_DAYS = 365
# Предохранитель: максимум отзывов на один товар в итоговом файле.
MAX_REVIEWS_PER_PRODUCT = 500
# Собираем с запасом к лимиту: часть отзывов отсеют фильтры (период, вариант,
# пустые), поэтому набираем кратно больше, чтобы лимит был достижим.
COLLECT_OVERSHOOT = 3
# Страниц вопросов максимум (анонимно Ozon отдаёт ~90 вопросов = ~9 страниц).
QUESTION_PAGES = 12

# --- статистика ------------------------------------------------------------
# Окна для сводки оценок. 30/90 — свежая динамика, 180/365 — фон за год.
STATS_WINDOWS_DAYS = (30, 90, 180, 365)
# Ozon отдаёт даты отзывов в московском времени; при другой зоне даты сместятся.
TIMEZONE = "Europe/Moscow"

# Куда разрешено переходить. Без этого списка в браузере пользователя открылось бы
# что угодно из чужого urls.txt — включая file:// и адреса локальной сети.
ALLOWED_SCHEMES = ("http", "https")
ALLOWED_HOST_SUFFIX = "ozon.ru"

# --- темп запросов ---------------------------------------------------------
# Случайные паузы (секунды): держат нагрузку ниже порога rate-limit Ozon.
PAGE_DELAY = (1.0, 3.0)      # между прокрутками карточки (bootstrap)
FETCH_DELAY = (0.15, 0.35)   # между курсорными запросами отзывов
PRODUCT_DELAY = (3.0, 6.0)   # между товарами

# --- пагинация и распознавание конца ленты ---------------------------------
# Прокруток карточки, чтобы браузер сам сходил в API и мы сняли его заголовки.
# 12 с запасом: обычно хватает 2-3, но на медленной загрузке нужно больше.
HEADER_SCROLLS = 12
# Абсолютный предохранитель от бесконечной пагинации (~120к отзывов при 30 на
# страницу) на случай, если Ozon начнёт отдавать зацикленный курсор.
MAX_FETCH_PAGES = 4000
# Столько страниц подряд без НОВЫХ отзывов считаем концом ленты. Не 1, потому
# что Ozon штатно повторяет уже виденные отзывы на стыках страниц.
EMPTY_PAGES_LIMIT = 8

# --- капча -----------------------------------------------------------------
# Сколько ждать, пока пользователь решит капчу в окне: 75 попыток по 4 с = 5 мин.
CAPTCHA_WAIT_ITERS = 75
CAPTCHA_POLL_MS = 4000

# --- браузер ---------------------------------------------------------------
# Только реальный установленный Chrome: Chromium из поставки Playwright Ozon
# определяет как автоматизацию и отдаёт 403 (проверено опытным путём).
BROWSER_CHANNEL = "chrome"
# 60 с — карточка Ozon с холодным профилем и анти-бот-проверкой грузится до ~30 с;
# берём двойной запас, чтобы медленный интернет не ронял сбор.
NAV_TIMEOUT_MS = 60_000
# Пауза после открытия карточки, чтобы страница успела сходить в API.
PAGE_SETTLE_MS = 2500
# На сколько пикселей крутим колесо за один шаг bootstrap.
SCROLL_STEP_PX = 3000

# --- самопроверка (--doctor) ----------------------------------------------
DOCTOR_MIN_CHARS = 5         # меньше 5 характеристик = парсер что-то потерял
DOCTOR_MAX_REVIEWS = 20      # проверке хватает нескольких страниц

# --- логирование -----------------------------------------------------------
LOG_LEVEL = logging.INFO

# --- пути (BASE_DIR — корень проекта, на уровень выше пакета) --------------
BASE_DIR = Path(__file__).resolve().parent.parent
OUTPUT_DIR = BASE_DIR / "output"     # сюда пишутся {product_id}.json
PROFILE_DIR = BASE_DIR / ".profile"  # сохранённая сессия/cookie браузера
LOG_DIR = BASE_DIR / "logs"          # logs/reviews.log


def delay_ms(bounds: tuple[float, float]) -> float:
    """Случайная пауза из диапазона (секунды) в миллисекундах — их ждёт Playwright."""
    return random.uniform(*bounds) * 1000


def _validate() -> None:
    """Ловит опечатку в настройках при импорте, а не через полчаса сбора."""
    for name in ("PAGE_DELAY", "FETCH_DELAY", "PRODUCT_DELAY"):
        lo, hi = globals()[name]
        if not 0 <= lo <= hi:
            raise ValueError(f"config.{name}: ожидалось 0 <= min <= max, получено {(lo, hi)}")
    positive = ("REVIEW_PERIOD_DAYS", "MAX_REVIEWS_PER_PRODUCT", "COLLECT_OVERSHOOT",
                "QUESTION_PAGES", "HEADER_SCROLLS", "MAX_FETCH_PAGES", "EMPTY_PAGES_LIMIT",
                "CAPTCHA_WAIT_ITERS", "CAPTCHA_POLL_MS", "NAV_TIMEOUT_MS")
    for name in positive:
        if globals()[name] <= 0:
            raise ValueError(f"config.{name}: ожидалось положительное число, получено {globals()[name]}")
    if not STATS_WINDOWS_DAYS or any(d <= 0 for d in STATS_WINDOWS_DAYS):
        raise ValueError(f"config.STATS_WINDOWS_DAYS: только положительные дни, получено {STATS_WINDOWS_DAYS}")


_validate()
