"""Типы ошибок парсера — чтобы причина сбоя была видна, а не спрятана.

Раньше любой сбой (нет заголовков, 403, битый JSON) приводил к пустому результату
без объяснения. Эти исключения называют причину и всплывают до пользователя.
"""


class OzonParserError(Exception):
    """Базовая ошибка парсера."""


class BootstrapError(OzonParserError):
    """Не удалось подготовить сессию: нет заголовков API или не определён товар."""


class CaptchaTimeout(OzonParserError):
    """Капча/блокировка не была снята за отведённое время."""


class BrowserNotFound(OzonParserError):
    """Не найден исполняемый файл Chrome."""
